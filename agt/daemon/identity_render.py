"""Identity AGENTS.md renderer + path helpers (daemon-side, stdlib only).

Mirrors the rendering logic in ``agt.server.services.identity_service`` so
the daemon can materialize ``~/.agt/identities/<slug>/AGENTS.md`` from a
JSON dict returned by ``GET /api/identities/{did}`` without pulling in any
server-only dependencies (SQLAlchemy, ``IdentityModel``, etc.).

Kept intentionally tiny — no imports beyond the standard library. If the
server-side renderer grows new fields, mirror them here so the on-disk
mirror stays identical to what ``agt identity create`` would have written
locally.

Public surface:
- ``render_agent_md(identity: dict) -> str``
- ``dir_name_for_did(did: str) -> str``
- ``local_agent_md_path(did: str) -> Path``
"""

from __future__ import annotations

import hashlib
import json
import re
from pathlib import Path
from typing import Any


# Same slug pattern as the server-side renderer; ``did:agt:<slug>`` so the
# last segment after ``:`` is the directory name. A malformed DID falls
# back to a hash to avoid surprising path traversal.
_SLUG_PATTERN = re.compile(r"^[a-z0-9][a-z0-9-]{0,62}[a-z0-9]$")


def dir_name_for_did(did: str) -> str:
    """Extract the directory name from a DID.

    Returns ``<slug>`` when the DID matches ``did:agt:<slug>``; otherwise a
    hash-based fallback (``identity-<hash8>``) that won't collide with any
    valid slug.
    """
    parts = did.split(":")
    if len(parts) == 3 and parts[0] == "did":
        slug = parts[-1]
        if _SLUG_PATTERN.match(slug):
            return slug
        return f"{slug}-{hashlib.sha256(did.encode()).hexdigest()[:8]}"
    return f"identity-{hashlib.sha256(did.encode()).hexdigest()[:8]}"


def local_agent_md_path(did: str) -> Path:
    """The on-disk path an AGENTS.md mirror would live at for ``did``.

    Uses ``Path.home()`` (the daemon process's home) so the result matches
    where ``_inject_identity`` looks. Always returns a path — the file may
    or may not exist; callers check existence.
    """
    return Path.home() / ".agt" / "identities" / dir_name_for_did(did) / "AGENTS.md"


def render_agent_md(identity: dict[str, Any]) -> str:
    """Render identity JSON into AGENTS.md content.

    The dict shape matches what ``GET /api/identities/{did}`` returns
    (see ``IdentityOut`` schema): ``did``, ``name``, ``description``,
    ``capabilities`` (list of str), ``status``, ``daemon_id``,
    ``updated_at``, etc. Extra fields are ignored — we only consume what
    the renderer needs.

    Output is byte-identical (modulo trailing whitespace) to what the
    server-side ``write_agent_md`` produces for the same identity record.
    """
    did = identity.get("did", "")
    name = identity.get("name", "")
    description = identity.get("description", "")
    capabilities = identity.get("capabilities", "[]")
    status = identity.get("status", "active")
    daemon_id = identity.get("daemon_id", "")

    # The schema returns capabilities as a list, but be defensive in case
    # a future schema variant ships it as a JSON string.
    if isinstance(capabilities, str):
        try:
            caps_list = json.loads(capabilities)
        except json.JSONDecodeError:
            caps_list = []
    else:
        caps_list = capabilities or []

    caps_md = (
        "\n".join(f"- {cap}" for cap in caps_list)
        if caps_list
        else "*(No capabilities defined)*"
    )

    return f"""<!-- Auto-generated by AGT. Manual edits will be preserved unless regenerated. -->

# {name}

**DID**: `{did}`
**Daemon**: `{daemon_id}`
**Status**: `{status}`

## Description
{description or "*(No description provided)*"}

## Capabilities
{caps_md}

## Working Style
*(Optional: Describe the working style, preferences, or constraints for this identity.)*
"""


__all__ = ["render_agent_md", "dir_name_for_did", "local_agent_md_path"]
