"""Renderer for identity AGENTS.md mirrors (daemon-side, stdlib-only).

The daemon mirrors ``~/.agt/identities/<slug>/AGENTS.md`` from the server's
JSON so a remote daemon can inject an identity whose AGENTS.md was
originally written on the CLI machine. This module tests the renderer's
output shape and the path helpers.
"""

from __future__ import annotations

from pathlib import Path

import pytest

from agt.daemon.identity_render import (
    dir_name_for_did,
    local_agent_md_path,
    render_agent_md,
)


def _full_identity(**overrides):
    """A realistic ``GET /api/identities/{did}`` response shape."""
    base = {
        "did": "did:agt:code-reviewer",
        "daemon_id": "d-uuid5-form",
        "name": "Code Reviewer",
        "description": "Reviews PRs for style, correctness, and tests.",
        "capabilities": ["python", "code-review", "pytest"],
        "status": "active",
        "visibility": "private",
        "created_by": "alice",
        "created_at": "2026-08-20 10:00:00",
        "updated_at": "2026-08-25 14:23:11",
    }
    base.update(overrides)
    return base


class TestRenderAgentMd:
    def test_full_identity_includes_all_sections(self):
        out = render_agent_md(_full_identity())
        # Header banner (must match the server's format so the file is
        # byte-equivalent to what ``agt identity create`` wrote locally).
        assert out.startswith("<!-- Auto-generated by AGT.")
        # Identity metadata.
        assert "# Code Reviewer" in out
        assert "**DID**: `did:agt:code-reviewer`" in out
        assert "**Daemon**: `d-uuid5-form`" in out
        assert "**Status**: `active`" in out
        # Description.
        assert "## Description" in out
        assert "Reviews PRs for style" in out
        # Capabilities as bullet list.
        assert "## Capabilities" in out
        assert "- python" in out
        assert "- code-review" in out
        assert "- pytest" in out
        # Working Style section.
        assert "## Working Style" in out

    def test_empty_description_shows_placeholder(self):
        out = render_agent_md(_full_identity(description=""))
        assert "*(No description provided)*" in out

    def test_missing_description_shows_placeholder(self):
        ident = _full_identity()
        del ident["description"]
        out = render_agent_md(ident)
        assert "*(No description provided)*" in out

    def test_empty_capabilities_shows_placeholder(self):
        out = render_agent_md(_full_identity(capabilities=[]))
        assert "*(No capabilities defined)*" in out

    def test_capabilities_as_json_string_is_parsed(self):
        """Defensive: schema variant that ships capabilities as a JSON string."""
        out = render_agent_md(_full_identity(capabilities='["python", "lint"]'))
        assert "- python" in out
        assert "- lint" in out

    def test_corrupt_capabilities_json_falls_back_empty(self):
        """Garbage JSON for capabilities → empty list → placeholder."""
        out = render_agent_md(_full_identity(capabilities="not-json{"))
        assert "*(No capabilities defined)*" in out

    def test_status_variants_appear_verbatim(self):
        out = render_agent_md(_full_identity(status="deprecated"))
        assert "**Status**: `deprecated`" in out


class TestDirNameForDid:
    def test_valid_did_returns_slug(self):
        assert dir_name_for_did("did:agt:code-reviewer") == "code-reviewer"

    def test_did_with_long_slug_accepted(self):
        slug = "a" + "b" * 62  # 63 chars total, leading letter + 62 alnum
        assert dir_name_for_did(f"did:agt:{slug}") == slug

    def test_malformed_did_uses_hash_fallback(self):
        # Two segments instead of three → fallback path.
        name = dir_name_for_did("not-a-did")
        assert name.startswith("identity-")
        assert len(name) == len("identity-") + 8

    def test_did_with_bad_slug_chars_uses_hash_suffix(self):
        # Slug with uppercase — not valid per pattern → fallback.
        name = dir_name_for_did("did:agt:BadSlug")
        # ``BadSlug`` violates the lowercase rule; renderer should NOT
        # return it raw (would be case-sensitive on case-insensitive FS,
        # and risky for shell use).
        assert name.startswith("BadSlug-")
        assert len(name) > len("BadSlug")


class TestLocalAgentMdPath:
    def test_path_under_home(self, monkeypatch: pytest.MonkeyPatch, tmp_path: Path):
        monkeypatch.setattr("pathlib.Path.home", lambda: tmp_path)
        path = local_agent_md_path("did:agt:code-reviewer")
        assert path == tmp_path / ".agt" / "identities" / "code-reviewer" / "AGENTS.md"

    def test_hash_fallback_for_malformed_did(self, monkeypatch: pytest.MonkeyPatch, tmp_path: Path):
        monkeypatch.setattr("pathlib.Path.home", lambda: tmp_path)
        path = local_agent_md_path("not-a-did")
        # Falls back to ``identity-<hash8>`` directory.
        assert path.parent.name.startswith("identity-")
        assert path.name == "AGENTS.md"
